test('default workshop publishes only the new account handle and safe defaults',async()=>{
 const calls=[],tx=async(parts,...args)=>{calls.push({sql:parts.join('?'),args});return calls.length===2?[{username:'technic_test'}]:[]};tx.json=v=>v
 await createDefaultWorkshop(tx,'account-id')
 assert.match(calls[0].sql,/set_config/)
 assert.equal(calls[2].args[1],'technic_test')
 assert.equal(calls[2].args[2].blocks.find(b=>b.key==='awards').visible,true)
 assert.equal(calls[2].args[2].blocks.find(b=>b.key==='activity').visible,false)
 assert.doesNotMatch(calls[2].sql,/email|password|document/)
})
test('both account registration flows create a public workshop; hiding removes it from ranking',{skip:process.env.BRICKLAB_COMMERCE_INTEGRATION!=='1'},async()=>{
 assert.equal(process.env.PGDATABASE,'bricklab_commerce_check')
 const store=connectAuthStore(),handle='test_'+randomBytes(6).toString('hex'),verifiedHandle='test_'+randomBytes(6).toString('hex'),email=randomUUID()+'@example.invalid',token=randomBytes(32).toString('hex')
 try{
  const owner=await store.register({email:randomUUID()+'@example.invalid',displayName:handle,passwordHash:'test-hash',tokenHash:token,expiresAt:new Date(Date.now()+3600000)})
  const card=await store.getPublicCard(handle);assert.equal(card.username,handle);assert.equal(card.unified,true);assert.equal(card.portfolio.blocks.find(b=>b.key==='awards').visible,true)
  assert.equal((await store.getOwnCard(owner.id)).id,card.id)
  assert.ok((await store.getAchievementRankings(0)).some(r=>r.id===card.id&&r.username===handle))
  const ranked=(await store.getAchievementRankings(0)).find(r=>r.id===card.id)
  assert.equal((await store.workshopPublicSummary(card.id)).rank,ranked.position)
  await store.saveProfile(owner.id,{bio:'',cover:'blueprint',metricLayout:['rank','likes']})
  assert.deepEqual((await store.getProfile(owner.id)).metricLayout,['rank','likes'])
  assert.deepEqual((await store.workshopPublicSummary(card.id)).layout,['rank','likes'])
  await store.saveProfile(owner.id,{bio:'',cover:'blueprint',metricLayout:[]})
  assert.deepEqual((await store.workshopPublicSummary(card.id)).layout,[])
  const project=await store.createProject(owner.id,{format:'bricklab-3d',version:1,name:'Visibility fixture',parts:[{id:'part',design:'3001',position:[0,0,0]}],connections:[]})
  await store.publishBuild(owner.id,project.id,{revision:project.revision,description:'Visibility fixture',category:'mechanisms'})
  const [build]=await store.listOwnBuilds(owner.id)
  const reader=await store.register({email:randomUUID()+'@example.invalid',displayName:'test_'+randomBytes(6).toString('hex'),passwordHash:'test-hash',tokenHash:randomBytes(32).toString('hex'),expiresAt:new Date(Date.now()+3600000)})
  await store.addComment(reader.id,build.id,{body:'Preserve this discussion',parentId:null})
  await store.setSocial(reader.id,'like',build.id,true)
  await store.setSocial(reader.id,'follow',card.id,true)
  await store.hideCard(owner.id)
  assert.equal((await store.getOwnCard(owner.id)).visible,false)
  const layout={...card.portfolio,blocks:card.portfolio.blocks.map(b=>({...b,span:b.key==='featured'?8:4,...(b.key==='publications'?{newRow:true}:{})})),featured:build.id,collections:[{title:'Test collection',ids:[build.id]}]}
  await store.savePortfolio(owner.id,layout)
  const hidden=await store.getOwnCard(owner.id)
  assert.equal(hidden.visible,false);assert.equal(hidden.displayName,card.displayName);assert.equal(hidden.bio,card.bio)
  assert.deepEqual(hidden.portfolio,layout)
  assert.equal((await store.listOwnBuilds(owner.id))[0].id,build.id)
  assert.equal(await store.getPublicBuild(build.id),undefined)
  assert.equal(await store.getPublicBuild(build.id,true),undefined)
  assert.equal((await store.listPublicBuilds(card.id)).length,0)
  await assert.rejects(store.listComments(build.id))
  assert.equal(await store.workshopPublicSummary(card.id),null)
  assert.ok(!(await store.getAchievementRankings(0)).some(r=>r.id===card.id))
  await store.publishCard(owner.id,{displayName:handle,bio:'',cover:'blueprint',showAvatar:true,showCover:true,showBackground:true,unified:true,portfolio:layout,visible:true})
  assert.equal((await store.getPublicCard(handle)).id,card.id)
  assert.deepEqual((await store.getPublicCard(handle)).portfolio,layout)
  assert.equal((await store.getPublicBuild(build.id)).likes,1)
  assert.equal((await store.getOwnCard(owner.id)).followers,1)
  assert.equal((await store.listComments(build.id))[0].body,'Preserve this discussion')
  const live={...layout,blocks:toLiveBlocks(layout.blocks),featured:null,collections:[]}
  await store.savePortfolio(owner.id,live,['firstCloudSave'],true)
  const expected={...layout,blocks:live.blocks}
  const published=await store.getPublicCard(handle)
  assert.deepEqual(published.portfolio,expected)
  assert.deepEqual(published.achievementShowcase,['firstCloudSave'])
  assert.ok(Number.isFinite(Date.parse(published.achievementDetails.dates.firstCloudSave)))
  assert.deepEqual(Object.keys(published.achievementDetails.dates),['firstCloudSave'])
  await assert.rejects(store.savePortfolio(owner.id,{...live,blocks:live.blocks.map(b=>({...b,visible:false}))},['custom-nonexistent'],true),{message:'invalid_showcase'})
  assert.deepEqual((await store.getPublicCard(handle)).portfolio,expected)
  const withoutAwards={...live,blocks:live.blocks.map(b=>b.key==='awards'?{...b,visible:false}:b)}
  await store.savePortfolio(owner.id,withoutAwards,undefined,true)
  const noAwards=await store.getPublicCard(handle);assert.equal(noAwards.achievementDetails,null);assert.equal(noAwards.achievementShowcase,null)
  await store.savePortfolio(owner.id,live,undefined,true)
  await store.hideCard(owner.id)
  assert.equal(await store.workshopPublicSummary(card.id),null)
  assert.equal(await store.getPublicCard(handle),undefined)
  assert.ok(!(await store.getAchievementRankings(0)).some(r=>r.id===card.id))
  assert.ok(await store.getProfile(owner.id))
  assert.equal(await store.issueAccountToken(email,'register',token),true)
  assert.equal(await store.finishAccountToken(email,'register',token,'test-hash',verifiedHandle,verifiedHandle),true)
  assert.equal((await store.getPublicCard(verifiedHandle)).username,verifiedHandle)
 }finally{await store.close()}
})
