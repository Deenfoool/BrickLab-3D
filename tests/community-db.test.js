import {test} from 'node:test'
import assert from 'node:assert/strict'
import {randomUUID,randomBytes} from 'node:crypto'
test('publication options with PostgreSQL app role', {skip:process.env.BRICKLAB_TEST_DB!=='true'},async t=>{
 assert.equal(process.env.PGDATABASE,'bricklab_browser_test','Refusing to run fixtures in a non-test database')
 const {connectAuthStore}=await import('../server/db/auth-store.js')
 const store=connectAuthStore();t.after(()=>store.close());await store.ready()
 const register=displayName=>store.register({email:randomUUID()+'@example.invalid',displayName,passwordHash:'test-hash',tokenHash:randomBytes(32).toString('hex'),expiresAt:new Date(Date.now()+3600000)})
 const owner=await register('Hub Owner '+randomUUID()),reader=await register('Hub Reader '+randomUUID())
 await store.publishCard(owner.id,{displayName:owner.displayName,bio:''})
 await store.publishCard(reader.id,{displayName:reader.displayName,bio:''})
 const doc={format:'bricklab-3d',version:1,name:'Community test model',parts:[{id:'part',design:'3001',position:[0,0,0]}],connections:[]}
 const project=await store.createProject(owner.id,doc)
 const opts={revision:project.revision,description:'Test',category:'mechanisms',allowDownload:false,allowComments:false,allowRemix:false,tags:['test'],images:[Buffer.from('test-image')]}
 await store.publishBuild(owner.id,project.id,opts)
 await assert.rejects(store.saveProfile(owner.id,{bio:'',cover:'amber',background:'aurora'}),{message:'background_locked'})
 await store.publishCard(owner.id,{displayName:owner.displayName,bio:'',showBackground:true})
 await store.saveProfile(owner.id,{bio:'',cover:'amber',background:'first-build'})
 assert.equal((await store.getOwnCard(owner.id)).backgroundTheme,'first-build')
 assert.equal((await store.listPublicBuilds(null,{})).find(b=>b.authorId!==undefined&&b.author===owner.displayName)?.authorTheme,'first-build')
 await store.publishCard(owner.id,{displayName:owner.displayName,bio:'',showBackground:false})
 await store.saveProfile(owner.id,{bio:'',cover:'amber',background:'default'})
 assert.equal((await store.getOwnCard(owner.id)).backgroundTheme,null)
 const [build]=await store.listOwnBuilds(owner.id)
 assert.equal(build.allowDownload,false);assert.equal(build.allowComments,false);assert.equal(build.imageCount,1)
 assert.deepEqual(await store.getBuildImage(build.id,0),Buffer.from('test-image'))
 await assert.rejects(store.addComment(reader.id,build.id,{body:'Blocked',parentId:null}),{message:'comments_disabled'})
 await store.setSocial(reader.id,'bookmark',build.id,true)
 assert.ok((await store.listPublicBuilds(null,{bookmarkUid:reader.id})).some(b=>b.id===build.id))
 assert.ok(!(await store.listPublicBuilds(null,{bookmarkUid:owner.id})).some(b=>b.id===build.id))
 await store.reportBuild(reader.id,build.id,'copyright')
 await store.publishBuild(owner.id,project.id,{...opts,allowDownload:true,allowComments:true,allowRemix:true,images:undefined})
 const updated=await store.getPublicBuild(build.id);assert.equal(updated.allowRemix,true);assert.equal(updated.imageCount,1)
 assert.equal((await store.getPublicBuild(build.id,true)).allowDownload,true)
 await store.addComment(reader.id,build.id,{body:'Allowed',parentId:null})
 assert.ok((await store.listPublicCards(owner.displayName)).some(p=>p.displayName===owner.displayName))
 assert.ok((await store.listPublicBuilds(null,{week:true})).some(b=>b.id===build.id))
 const remix=await store.createProject(reader.id,{...doc,name:'Remix',communityOrigin:{id:build.id}})
 await store.publishBuild(reader.id,remix.id,{revision:remix.revision,description:'Remix',category:'mechanisms',allowDownload:true})
 const [derived]=await store.listOwnBuilds(reader.id)
 assert.equal(derived.originId,build.id);assert.equal(derived.workType,'remix');assert.ok(derived.attribution.includes(owner.displayName))
 await store.publishBuild(owner.id,project.id,{...opts,images:undefined})
 await assert.rejects(store.publishBuild(reader.id,remix.id,{revision:remix.revision,description:'Remix'}),{message:'remix_disabled'})
})

test('admin can equip and publish all premium themes without a payment', {skip:process.env.BRICKLAB_TEST_DB!=='true'},async t=>{
 assert.equal(process.env.PGDATABASE,'bricklab_browser_test')
 const uid=process.env.BRICKLAB_TEST_ADMIN_ID
 assert.match(uid??'',/^[0-9a-f-]{36}$/i)
 const {connectAuthStore}=await import('../server/db/auth-store.js')
 const {themeIds}=await import('../src/menu/store-themes.js')
 const store=connectAuthStore();t.after(()=>store.close())
 const initial=await store.getProfile(uid)
 assert.equal(initial.inventory.filter(i=>i.adminAccess===true&&i.owned).length,6)
 assert.equal(initial.inventory.find(i=>i.id==='first-build').owned,false)
 assert.equal((await store.testOrders(uid)).length,0)
 await store.publishCard(uid,{displayName:'Test admin theme',bio:'',showBackground:true})
 for(const id of themeIds){
  await store.saveProfile(uid,{bio:'',cover:'amber',background:id})
  assert.equal((await store.getProfile(uid)).background,id)
  assert.equal((await store.getOwnCard(uid)).backgroundTheme,id)
 }
 await store.publishCard(uid,{displayName:'Test admin theme',bio:'',showBackground:false})
 await store.saveProfile(uid,{bio:'',cover:'amber',background:'carbon'})
 assert.equal((await store.getOwnCard(uid)).backgroundTheme,null)
 assert.equal((await store.testOrders(uid)).length,0)
})

test('unified profile synchronizes only opt-in data, filters public build IDs, retains stable link', {skip:process.env.BRICKLAB_TEST_DB!=='true'},async t=>{
 assert.equal(process.env.PGDATABASE,'bricklab_browser_test')
 const {connectAuthStore}=await import('../server/db/auth-store.js')
 const {defaultPortfolio}=await import('../src/menu/portfolio-model.js')
 const {publicCard}=await import('../server/community.js')
 const store=connectAuthStore();t.after(()=>store.close())
 const user=await store.register({email:randomUUID()+'@example.invalid',displayName:'Unified test',passwordHash:'test-hash',tokenHash:randomBytes(32).toString('hex'),expiresAt:new Date(Date.now()+3600000)})
 await store.saveProfile(user.id,{bio:'private',cover:'amber'})
 await store.publishCard(user.id,{displayName:'Legacy name',bio:'legacy public'})
 const legacy=await store.getOwnCard(user.id)
 await store.saveProfile(user.id,{bio:'still private',cover:'amber'})
 assert.equal((await store.getOwnCard(user.id)).bio,'legacy public')
 const p=defaultPortfolio();p.blocks.find(b=>b.key==='awards').visible=true
 const input={displayName:'Unified name',bio:'Unified biography',cover:'blueprint',unified:true,showAvatar:false,showCover:false,showBackground:false,portfolio:p}
 await store.publishCard(user.id,input)
 assert.equal((await store.getProfile(user.id)).displayName,'Unified name')
 assert.equal((await store.getOwnCard(user.id)).id,legacy.id)
 const before=publicCard(await store.getPublicCard(legacy.id))
 assert.deepEqual(before.awards,[])
 const project=await store.createProject(user.id,{format:'bricklab-3d',version:1,name:'Unified build',parts:[{id:'part',design:'3001',position:[0,0,0]}],connections:[]})
 await store.publishBuild(user.id,project.id,{revision:project.revision,description:'',category:'mechanisms'})
 const [b]=await store.listOwnBuilds(user.id)
 p.featured=b.id;p.collections=[{title:'Engines',ids:[b.id,randomUUID()]}]
 await store.publishCard(user.id,{...input,portfolio:p})
 const card=publicCard(await store.getPublicCard(legacy.id))
 assert.equal(card.portfolio.featured,b.id);assert.deepEqual(card.portfolio.collections,[{title:'Engines',ids:[b.id]}]);assert.deepEqual(card.awards,['firstCloudSave'])
 await store.saveMedia(user.id,'avatar',Buffer.from('private avatar'))
 assert.equal(publicCard(await store.getPublicCard(legacy.id)).avatarUrl,null)
 await store.publishCard(user.id,{...input,portfolio:p,showAvatar:true})
 assert.ok(publicCard(await store.getPublicCard(legacy.id)).avatarUrl)
 await store.deleteMedia(user.id,'avatar')
 assert.equal(publicCard(await store.getPublicCard(legacy.id)).avatarUrl,null)
 await store.saveProfile(user.id,{displayName:'New unified name',bio:'Synced',cover:'amber'})
 const synced=publicCard(await store.getPublicCard(legacy.id))
 assert.equal(synced.displayName,'New unified name');assert.equal(synced.bio,'Synced');assert.equal(synced.coverTheme,null)
 assert.ok((await store.getActivity(user.id)).calendar.some(day=>day.count>=1))
 await store.unpublishCard(user.id)
 assert.equal(await store.getPublicCard(legacy.id),undefined)
 await store.publishCard(user.id,input)
 assert.equal((await store.getOwnCard(user.id)).id,legacy.id)
 assert.equal((await store.listOwnBuilds(user.id)).length,0)
})
