// Offline only. No geometry or metadata is downloaded by this script.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { resolve, relative } from 'node:path'
import { execFileSync } from 'node:child_process'

const [geometryRoot, shadowRoot, output = 'connectors-v4/inheritance-index-v4.js'] = process.argv.slice(2)
if (!geometryRoot || !shadowRoot) throw new Error('Usage: node scripts/index-connector-inheritance.mjs <ldraw checkout> <pinned shadow checkout> [output]')
const sha = root => execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim()
const shadowCommit = sha(shadowRoot)
if (shadowCommit !== 'f2fb70c55521e0dfdf2af4d26a87167d4d0d9eec') throw new Error('Unexpected Shadow snapshot')
async function files(root) {
  const result = new Map()
  async function walk(dir) {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      if (entry.name.startsWith('.')) continue
      const path = resolve(dir, entry.name)
      if (entry.isDirectory()) await walk(path)
      else if (entry.name.endsWith('.dat')) result.set(relative(root, path).replaceAll('\\', '/').toLowerCase(), path)
    }
  }
  await walk(resolve(root))
  return result
}
const geometry = await files(geometryRoot), shadow = await files(shadowRoot)
for (const path of geometry.keys()) if (!/^(parts|p)\//.test(path)) geometry.delete(path)
const edges = new Map(), used = new Set()
for (const [path, filename] of geometry) {
  const refs = new Set()
  for (const line of (await readFile(filename, 'utf8')).split(/\r?\n/)) {
    const t = line.trim().split(/\s+/)
    if (t[0] !== '1' || t.length < 15 || !t.slice(2,14).every(v => Number.isFinite(Number(v)))) continue
    const ref = t.slice(14).join(' ').replaceAll('\\', '/').toLowerCase()
    const candidates = /^(parts|p)\//.test(ref) ? [ref] : ref.startsWith('s/') ? [`parts/${ref}`]
      : path.startsWith('p/') || /^(8|48)\//.test(ref) ? [`p/${ref}`, `parts/${ref}`] : [`parts/${ref}`, `p/${ref}`]
    const child = candidates.find(v => geometry.has(v))
    if (child) { refs.add(child); used.add(child) }
  }
  edges.set(path, refs)
}
// A routing index, never connector definitions. Runtime still parses the actual
// geometry transforms and pinned metadata, including CLEAR and scale policies.
const reachable = new Set(shadow.keys())
for (let changed = true; changed;) {
  changed = false
  for (const [path, refs] of edges) if (!reachable.has(path) && [...refs].some(v => reachable.has(v))) {
    reachable.add(path); changed = true
  }
}
const paths = [...used].filter(path => [...edges.get(path)].some(v => reachable.has(v))).sort()
const info = { geometryCommit: sha(geometryRoot), shadowCommit, geometryFiles: geometry.size, shadowFiles: shadow.size, paths: paths.length }
await writeFile(output, `// Generated by scripts/index-connector-inheritance.mjs. See NOTICE_CONNECTORS.md.\nexport const INHERITANCE_INDEX_SOURCE_V4 = Object.freeze(${JSON.stringify(info)})\nexport const CONNECTOR_INHERITANCE_PATHS_V4 = new Set(\`${paths.join('\n')}\`.split('\\n'))\n`)
console.log(JSON.stringify(info))
